// gen-engine-lists.mjs — generates browser-safe engine contract constants in
// packages/schema/src/generated/engine-lists.ts from installed @ai-rpg-engine/content-schema.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
export const DEFAULT_REPO_ROOT = resolve(__dirname, '..');
export const GENERATED_REL_PATH = 'packages/schema/src/generated/engine-lists.ts';

function assertNonEmptyStringArray(value, name) {
  if (!Array.isArray(value) || value.length === 0 || !value.every((v) => typeof v === 'string' && v.length > 0)) {
    throw new Error(`Missing or invalid required export '${name}' from @ai-rpg-engine/content-schema`);
  }
  return [...value];
}

function assertNonEmptyStringRecord(value, name) {
  if (!value || typeof value !== 'object' || Array.isArray(value)) {
    throw new Error(`Missing or invalid required export '${name}' from @ai-rpg-engine/content-schema`);
  }
  const entries = Object.entries(value);
  if (entries.length === 0 || !entries.every(([k, v]) => typeof k === 'string' && k.length > 0 && typeof v === 'string')) {
    throw new Error(`Export '${name}' from @ai-rpg-engine/content-schema must be a non-empty Record<string, string>`);
  }
  return Object.fromEntries(entries);
}

/** Resolve installed `@ai-rpg-engine/content-schema` package dir and version from `repoRoot`. */
export function resolveInstalledContentSchemaInfo(repoRoot = DEFAULT_REPO_ROOT) {
  let dir = resolve(repoRoot);
  for (let i = 0; i < 10; i++) {
    const pkgDir = join(dir, 'node_modules', '@ai-rpg-engine', 'content-schema');
    const pkgJsonPath = join(pkgDir, 'package.json');
    if (existsSync(pkgJsonPath)) {
      const pkg = JSON.parse(readFileSync(pkgJsonPath, 'utf-8'));
      return { pkgDir, version: String(pkg.version ?? '') };
    }
    const parent = dirname(dir);
    if (parent === dir) break;
    dir = parent;
  }
  throw new Error(`@ai-rpg-engine/content-schema is not installed above ${repoRoot}`);
}

/** Compute bounded `>=major.minor.patch <(major+1).0.0` range from an installed version. */
export function computeEngineVersionRange(version) {
  const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(version);
  if (!m) {
    throw new Error(`Expected exact semver major.minor.patch for @ai-rpg-engine/content-schema, got "${version}"`);
  }
  const major = Number(m[1]);
  return `>=${version} <${major + 1}.0.0`;
}

function formatStringTupleConst(name, values) {
  const lines = [`export const ${name} = [`];
  for (const v of values) {
    lines.push(`  ${JSON.stringify(v)},`);
  }
  lines.push('] as const;');
  return lines.join('\n');
}

function formatStringRecordConst(name, record) {
  const lines = [`export const ${name} = {`];
  for (const [k, v] of Object.entries(record)) {
    const keyExpr = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(k) ? k : JSON.stringify(k);
    lines.push(`  ${keyExpr}: ${JSON.stringify(v)},`);
  }
  lines.push('} as const satisfies Record<string, string>;');
  return lines.join('\n');
}

/** Build the TypeScript source text for `packages/schema/src/generated/engine-lists.ts`. */
export function renderEngineListsModule({ version, schemaExports }) {
  const engineVersionRange = computeEngineVersionRange(version);
  const simAffectingKeys = assertNonEmptyStringArray(schemaExports.SIM_AFFECTING_KEYS, 'SIM_AFFECTING_KEYS');
  const allowedPackKeys = assertNonEmptyStringArray(schemaExports.ALLOWED_PACK_KEYS, 'ALLOWED_PACK_KEYS');
  const encounterAnchorTypes = assertNonEmptyStringArray(schemaExports.ENCOUNTER_ANCHOR_TYPES, 'ENCOUNTER_ANCHOR_TYPES');
  const evaluatedNotMappedKeys = assertNonEmptyStringRecord(
    schemaExports.EVALUATED_NOT_MAPPED_KEYS,
    'EVALUATED_NOT_MAPPED_KEYS',
  );

  const sections = [
    '// engine-lists.ts — GENERATED, DO NOT EDIT BY HAND.',
    '//',
    `// Generated by scripts/gen-engine-lists.mjs from @ai-rpg-engine/content-schema@${version}.`,
    '// Browser-safe static constants only — zero runtime imports from Node or engine packages.',
    '',
    `export const INSTALLED_ENGINE_VERSION = ${JSON.stringify(version)} as const;`,
    '',
    `export const ENGINE_VERSION_RANGE = ${JSON.stringify(engineVersionRange)} as const;`,
    '',
    formatStringTupleConst('SIM_AFFECTING_KEYS', simAffectingKeys),
    '',
    formatStringTupleConst('ALLOWED_PACK_KEYS', allowedPackKeys),
    '',
    formatStringTupleConst('ENCOUNTER_ANCHOR_TYPES', encounterAnchorTypes),
    '',
    formatStringRecordConst('EVALUATED_NOT_MAPPED_KEYS', evaluatedNotMappedKeys),
    '',
  ];

  return sections.join('\n');
}

/** Read installed `@ai-rpg-engine/content-schema` (or injected exports) and write generated TS module. */
export async function generateEngineLists(options = {}) {
  const repoRoot = options.repoRoot ?? DEFAULT_REPO_ROOT;
  const outPath = resolve(repoRoot, options.outRelPath ?? GENERATED_REL_PATH);

  let version = options.version;
  let schemaExports = options.schemaExports;
  if (!schemaExports || !version) {
    const info = resolveInstalledContentSchemaInfo(repoRoot);
    if (!version) version = info.version;
    if (!schemaExports) {
      const pkgJson = JSON.parse(readFileSync(join(info.pkgDir, 'package.json'), 'utf-8'));
      const entryRel =
        typeof pkgJson.exports === 'object' && pkgJson.exports?.['.']?.import
          ? pkgJson.exports['.'].import
          : typeof pkgJson.main === 'string'
            ? pkgJson.main
            : 'dist/index.js';
      const entryAbs = resolve(info.pkgDir, entryRel);
      schemaExports = await import(pathToFileURL(entryAbs).href);
    }
  }

  const content = renderEngineListsModule({ version, schemaExports });
  if (options.write !== false) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, content, 'utf-8');
  }
  return { outPath, version, content };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(__filename)) {
  const result = await generateEngineLists();
  console.log(`[gen-engine-lists] wrote ${result.outPath} (version=${result.version})`);
}
